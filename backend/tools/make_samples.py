def make_excel() -> Path:
    """生成:商品参数总表.xlsx(每行一个商品)"""
    path = SAMPLE_DIR / "商品参数总表.xlsx"
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "商品参数"

    # 写表头(加粗)
    ws.append(EXCEL_HEADERS)
    for cell in ws[1]:
        cell.font = openpyxl.styles.Font(bold=True)

    for row in PRODUCTS:
        ws.append(row)

    # 简单调一下列宽,方便查看
    for col, width in zip("ABCDEFGHI", [28, 14, 12, 28, 24, 14, 14, 10, 12]):
        ws.column_dimensions[col].width = width

    wb.save(path)
    print(f"✅ 已生成 {path.name}({len(PRODUCTS)} 个商品)")
    return path


